import { render, screen, waitFor } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import App from './App'
import { Button } from '@/components/ui/button'

test('invalid submit focuses its labelled field; successful submit adds one project and restores focus', async () => {
  const user = userEvent.setup()
  render(<App/>)
  const trigger = screen.getByRole('button', { name: '新建项目' })
  await user.click(trigger)
  const input = screen.getByRole('textbox', { name: '项目名称' })
  expect(input).toHaveFocus()
  await user.click(screen.getByRole('button', { name: '创建项目' }))
  expect(input).toHaveAttribute('aria-invalid', 'true')
  expect(input).toHaveAccessibleDescription('请输入项目名称')
  expect(input).toHaveFocus()
  await user.type(input, '体验实验室')
  await user.dblClick(screen.getByRole('button', { name: '创建项目' }))
  expect(screen.getByRole('button', { name: '创建中' })).toBeDisabled()
  await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
  expect(screen.getAllByRole('heading', { name: '体验实验室' })).toHaveLength(1)
  expect(screen.getByRole('status')).toHaveTextContent('已创建「体验实验室」')
  expect(trigger).toHaveFocus()
})

test('Escape cancels without changing projects; duplicate names keep dialog open', async () => {
  const user = userEvent.setup()
  render(<App/>)
  const trigger = screen.getByRole('button', { name: '新建项目' })
  await user.click(trigger)
  await user.type(screen.getByLabelText('项目名称'), '放弃的草稿')
  await user.keyboard('{Escape}')
  expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  expect(screen.queryByText('放弃的草稿')).not.toBeInTheDocument()
  expect(trigger).toHaveFocus()
  await user.click(trigger)
  expect(screen.getByLabelText('项目名称')).toHaveValue('')
  await user.type(screen.getByLabelText('项目名称'), '品牌升级')
  await user.click(screen.getByRole('button', { name: '创建项目' }))
  expect(screen.getByRole('dialog')).toBeInTheDocument()
  expect(screen.getByLabelText('项目名称')).toHaveAccessibleDescription('已有同名项目，请换一个名称')
})

test('tabs support keyboard activation; switch controls dependent checkbox', async () => {
  const user = userEvent.setup()
  render(<App/>)
  screen.getByRole('tab', { name: '项目' }).focus()
  await user.keyboard('{ArrowRight}')
  await waitFor(() => expect(screen.getByRole('tab', { name: '通知偏好' })).toHaveAttribute('aria-selected', 'true'))
  const toggle = screen.getByRole('switch', { name: '每日摘要' })
  toggle.focus()
  await user.keyboard(' ')
  expect(toggle).toHaveAttribute('aria-checked', 'false')
  expect(screen.getByRole('checkbox', { name: '通过邮件接收摘要' })).toBeDisabled()
  await user.keyboard(' ')
  const checkbox = screen.getByRole('checkbox', { name: '通过邮件接收摘要' })
  checkbox.focus()
  await user.keyboard(' ')
  expect(checkbox).toHaveAttribute('aria-checked', 'false')
})

test('modal traps Tab focus and theme toggles preserve local state', async () => {
  const user = userEvent.setup()
  render(<App/>)
  await user.click(screen.getByRole('button', { name: '切换深色主题' }))
  expect(document.documentElement).toHaveClass('dark')
  await user.click(screen.getByRole('button', { name: '新建项目' }))
  const dialog = screen.getByRole('dialog')
  for (let n = 0; n < 8; n++) { await user.tab(); expect(dialog.contains(document.activeElement)).toBe(true) }
  await user.keyboard('{Escape}')
  await user.click(screen.getByRole('button', { name: '切换浅色主题' }))
  expect(document.documentElement).not.toHaveClass('dark')
  expect(screen.getByText('共 2 个项目')).toBeInTheDocument()
})

